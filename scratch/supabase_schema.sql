-- Ensure the 'post-media' bucket exists and is set to public
INSERT INTO storage.buckets (id, name, public) 
VALUES ('post-media', 'post-media', true)
ON CONFLICT (id) DO NOTHING;

-- Ensure the 'avatars' bucket exists and is set to public
INSERT INTO storage.buckets (id, name, public) 
VALUES ('avatars', 'avatars', true)
ON CONFLICT (id) DO NOTHING;

-- Allow authenticated uploads to post-media
CREATE POLICY "Allow authenticated uploads to post-media"
ON storage.objects FOR INSERT TO authenticated WITH CHECK (bucket_id = 'post-media');

-- Allow public read access to post-media
CREATE POLICY "Allow public read access to post-media"
ON storage.objects FOR SELECT TO public USING (bucket_id = 'post-media');

-- Allow users to update their own files in post-media
CREATE POLICY "Allow users to update their own files in post-media"
ON storage.objects FOR UPDATE TO authenticated USING (bucket_id = 'post-media' AND (storage.foldername(name))[1] = auth.uid()::text);

-- Allow users to delete their own files in post-media
CREATE POLICY "Allow users to delete their own files in post-media"
ON storage.objects FOR DELETE TO authenticated USING (bucket_id = 'post-media' AND (storage.foldername(name))[1] = auth.uid()::text);

