-- ====================================================================
-- 2. CREATE TABLES
-- ====================================================================

-- User Profiles (Linked directly to Supabase Auth)
CREATE TABLE public.profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  username TEXT UNIQUE NOT NULL,
  display_name TEXT,         -- Added to match ProfileTab.js
  avatar_url TEXT,           -- Added to match ProfileTab.js
  email TEXT
);

-- Friendships System (Updated to match frontend sendFriendRequest logic)
CREATE TABLE public.friendships (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  receiver_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'accepted')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE(sender_id, receiver_id)
);

-- Daily Completed Tasks (Consolidated Post Table)
CREATE TABLE public.posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  task_title TEXT NOT NULL,          -- e.g., "Climbed a tree"
  media_url TEXT,                    -- URL link to Storage
  media_type TEXT DEFAULT 'photo',   -- 'photo' or 'video' based on your CameraCapture.js
  liked_by_users UUID[] DEFAULT '{}',-- Array of user IDs who liked it (Replaces the Likes table)
  comments JSONB DEFAULT '[]'::jsonb,-- JSON array storing comment objects [{user: 'x', text: 'y'}]
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ====================================================================
-- 3. CREATE AUTOMATIC SIGNUP TRIGGER
-- ====================================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, username)
  VALUES (
    new.id,
    new.email,
    -- Pulls custom username dynamically from your mobile app signup form data option
    coalesce(new.raw_user_meta_data->>'username', 'user_' || substr(new.id::text, 1, 8))
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

